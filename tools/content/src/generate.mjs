// Generator: validated content tree in, typed TypeScript data modules out.
// Same input gives the same bytes: keys are sorted and nothing time- or machine-dependent is written.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PAGE_KEYS, PAGE_ROUTES, recordKey, routeList } from './routes.mjs';
import { countCertifications, resolveDeep } from './tokens.mjs';
import { countLabel, formatErrors, lintTree, validateTree } from './validate.mjs';
import { loadTree } from './load.mjs';

export class ContentError extends Error {
  constructor(errors) {
    super(`Content validation failed (${countLabel(errors.length, 'error')}):\n${formatErrors(errors)}`);
    this.name = 'ContentError';
    this.errors = errors;
  }
}

const HEADER = '// GENERATED by tools/content/generate.mjs from the content config. Do not edit. Not committed.\n';

/** Key order of an image reference. Tools that scan the generated modules for references rely on it. */
const IMAGE_KEYS = ['id', 'w', 'h', 'widths'];
const isImageRef = (v) => IMAGE_KEYS.every((k) => k in v);

/** JSON with object keys sorted (image references keep id, w, h, widths first), so the output is stable. */
export function stableStringify(value, indent = 2) {
  const sort = (v) => {
    if (Array.isArray(v)) return v.map(sort);
    if (v !== null && typeof v === 'object') {
      const keys = Object.keys(v).sort();
      const ordered = isImageRef(v) ? [...IMAGE_KEYS, ...keys.filter((k) => !IMAGE_KEYS.includes(k))] : keys;
      return Object.fromEntries(ordered.map((k) => [k, sort(v[k])]));
    }
    return v;
  };
  return JSON.stringify(sort(value), null, indent);
}

/** Give a static image (an SVG that the site serves as a file) its site path. Image store references pass through. */
export function resolveStaticImages(value) {
  if (Array.isArray(value)) return value.map((v) => resolveStaticImages(v));
  if (value !== null && typeof value === 'object') {
    if (typeof value.src === 'string' && typeof value.alt === 'string') return { ...value, src: `/${value.src}` };
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveStaticImages(v)]));
  }
  return value;
}

/** One generated module: a type import line and one typed constant per export. */
const moduleSource = (types, exports) =>
  `${HEADER}import type { ${types.join(', ')} } from '../content.types';
` +
  exports.map(([name, type, value]) => `
export const ${name}: ${type} = ${stableStringify(value)};
`).join('');

const withoutKeys = (object, keys) => Object.fromEntries(Object.entries(object).filter(([k]) => !keys.includes(k)));

function certificationModules(files) {
  const itemFiles = Object.keys(files).filter((p) => p.startsWith('certifications/items/'));
  const items = Object.fromEntries(itemFiles.map((p) => [recordKey(p, 'certifications/items'), files[p]]));
  const toBadge = (slug) => {
    const item = items[slug];
    const badge = { name: item.name, kind: item.kind, status: item.status, vendor: item.vendor, image: item.image };
    if (item.url) return { ...badge, href: item.url };
    if (item.detail) return { ...badge, route: `/certifications/microsoft/${item.detail.type}/${item.detail.id}` };
    return badge;
  };
  const categories = files['certifications/categories.yaml'].categories.map((c) => ({ name: c.name, badges: c.items.map(toBadge) }));
  const details = {};
  for (const path of Object.keys(files).filter((p) => p.startsWith('certifications/details/'))) {
    const key = recordKey(path, 'certifications/details');
    details[key] = { type: key.split('/')[0], title: files[path].title, image: files[path].image };
  }
  const detailTypes = Object.fromEntries(files['certifications/detail-types.yaml'].types.map((t) => [t.id, t.name]));
  return { categories, details, detailTypes };
}

function speakingModules(files) {
  const events = {};
  const galleries = {};
  for (const path of Object.keys(files)) {
    if (path.startsWith('speaking/events/')) {
      const key = recordKey(path, 'speaking/events');
      const data = files[path];
      const links = data.links.map((l) => {
        const link = { title: l.title, image: l.image };
        if (l.label !== undefined) link.label = l.label;
        if (l.url !== undefined) link.href = l.url;
        if (l.gallery === true) link.route = `/public-speaking/${key.split('/')[0]}/photos/${key.split('/')[1]}`;
        return link;
      });
      events[key] = { ...withoutKeys(data, ['listing', 'links', 'body']), body: data.body ?? [], links };
    } else if (path.startsWith('speaking/galleries/')) {
      galleries[recordKey(path, 'speaking/galleries')] = files[path];
    }
  }
  const index = files['pages/public-speaking.yaml'].years.map((year) => ({
    name: year.name,
    talks: year.events.map((ref) => {
      const { name, image } = files[`speaking/events/${ref}.yaml`].listing;
      return { name, route: `/public-speaking/${ref}`, image };
    }),
  }));
  return { events, galleries, index };
}

/** Small summaries of the dynamic pages, for the SEO tags, so the full records stay in their lazy chunks. */
function recordSummaries(events, galleries, details) {
  const out = {};
  for (const [key, e] of Object.entries(events)) {
    out[`/public-speaking/${key}`] = { kind: 'event', title: e.title, year: e.year, ...(e.heading ? { heading: e.heading } : {}) };
  }
  for (const [key, g] of Object.entries(galleries)) {
    const [event, edition] = key.split('/');
    out[`/public-speaking/${event}/photos/${edition}`] = { kind: 'gallery', title: g.title, year: g.year };
  }
  for (const [key, d] of Object.entries(details)) out[`/certifications/microsoft/${key}`] = { kind: 'certificate', title: d.title };
  return out;
}

function prerenderParams(events, galleries, details) {
  const pair = (key, a, b) => ({ [a]: key.slice(0, key.indexOf('/')), [b]: key.slice(key.indexOf('/') + 1) });
  return {
    certDetails: Object.keys(details).map((k) => pair(k, 'type', 'id')),
    events: Object.keys(events).map((k) => pair(k, 'event', 'year')),
    galleries: Object.keys(galleries).map((k) => pair(k, 'event', 'year')),
  };
}

/**
 * Turn a loaded tree into generated modules. Throws ContentError when the tree is invalid (fails closed).
 * @returns {{ modules: Record<string, string>, hash: string, counts: {aws: number, microsoft: number}, routes: string[] }}
 */
export function buildModules(tree) {
  const errors = validateTree(tree);
  if (errors.length > 0) throw new ContentError(errors);

  const itemEntries = Object.entries(tree.files).filter(([p]) => p.startsWith('certifications/items/'));
  const counts = countCertifications(Object.fromEntries(itemEntries.map(([p, v]) => [recordKey(p, 'certifications/items'), v])));
  const files = resolveStaticImages(resolveDeep(tree.files, { aws: counts.aws, microsoft: counts.microsoft }));
  const page = (key) => files[`pages/${key}.yaml`];
  const own = (key) => withoutKeys(page(key), ['title', 'description', 'heading', 'breadcrumb']);

  const pages = Object.fromEntries(
    PAGE_KEYS.map((key) => {
      const { title, description, heading, breadcrumb } = page(key);
      const optional = Object.fromEntries(Object.entries({ description, heading, breadcrumb }).filter(([, value]) => value !== undefined));
      return [key, { route: PAGE_ROUTES[key] ?? '/404', title, ...optional }];
    }),
  );
  const cert = certificationModules(files);
  const speaking = speakingModules(files);
  const routes = routeList(tree.files);
  const single = (type, name, value) => moduleSource([type], [[name.toUpperCase().replace(/-/g, '_'), type, value]]);
  const modules = {
    'site.ts': single('SiteContent', 'site', { copyright: files['site.yaml'].copyright, name: files['site.yaml'].name }),
    'pages.ts': single('PagesContent', 'pages', pages),
    'home.ts': single('HomeContent', 'home', withoutKeys(page('home'), ['title', 'description'])),
    'biography.ts': single('BiographyContent', 'biography', own('biography')),
    'not-found.ts': single('NotFoundContent', 'not-found', own('not-found')),
    'cv.ts': single('CvContent', 'cv', own('cv')),
    'career-history.ts': single('CareerHistoryContent', 'career-history', own('career-history')),
    'portfolio.ts': single('PortfolioContent', 'portfolio', own('portfolio')),
    'projects.ts': single('ProjectsContent', 'projects', own('projects')),
    'blog.ts': single('BlogContent', 'blog', own('blog')),
    'current-role.ts': single('CurrentRoleContent', 'current-role', own('current-role')),
    'social.ts': single('SocialContent', 'social', own('social-media')),
    'tech-stack.ts': single('TechStackContent', 'tech-stack', own('tech-stack')),
    'special-awards.ts': single('SpecialAwardsContent', 'special-awards', own('special-awards')),
    'certifications.ts': moduleSource(
      ['CertCategory', 'CertDetail'],
      [
        ['CERT_CATEGORIES', 'CertCategory[]', cert.categories],
        ['CERT_DETAIL_TYPES', 'Record<string, string>', cert.detailTypes],
        ['CERT_DETAILS', 'Record<string, CertDetail>', cert.details],
      ],
    ),
    'speaking.ts': moduleSource(
      ['EventContent', 'GalleryContent', 'YearGroup'],
      [
        ['EVENTS', 'Record<string, EventContent>', speaking.events],
        ['GALLERIES', 'Record<string, GalleryContent>', speaking.galleries],
        ['SPEAKING_INDEX', 'YearGroup[]', speaking.index],
      ],
    ),
    'records.ts': single('RecordSummaries', 'records', recordSummaries(speaking.events, speaking.galleries, cert.details)),
    'prerender.ts': moduleSource(
      ['PrerenderParams'],
      [
        ['PRERENDER_PARAMS', 'PrerenderParams', prerenderParams(speaking.events, speaking.galleries, cert.details)],
        ['ROUTE_LIST', 'string[]', routes],
      ],
    ),
    'meta.ts': `${HEADER}
export const CONTENT_HASH = '${tree.hash}';
`,
  };
  return { modules, hash: tree.hash, counts, routes };
}

/** Write modules into outDir, removing generated files that are no longer produced. */
export function writeModules(outDir, result, fs = { mkdirSync, readdirSync, rmSync, writeFileSync }) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const stale of fs.readdirSync(outDir)) {
    if (!(stale in result.modules) && stale !== 'content-hash.txt') fs.rmSync(join(outDir, stale), { force: true });
  }
  for (const [name, source] of Object.entries(result.modules)) fs.writeFileSync(join(outDir, name), source);
  fs.writeFileSync(join(outDir, 'content-hash.txt'), `${result.hash}\n`);
}

/** Value of a `--name value` flag, or undefined. */
function flag(argv, name) {
  const at = argv.indexOf(name);
  return at >= 0 ? argv[at + 1] : undefined;
}

/**
 * CLI entry. Returns the process exit code. Prints counts and the hash, never content.
 * Flags: --src <config root> (else CONTENT_SRC, else <repo>/content-src), --expect-counts aws=4,microsoft=19.
 */
export function main({ root, env, argv = [], out = console.log, err = console.error, load = loadTree, write = writeModules }) {
  const source = flag(argv, '--src') ?? env.CONTENT_SRC ?? join(root, 'content-src');
  try {
    const tree = load(source);
    const result = buildModules(tree);
    const warnings = lintTree(tree);
    if (warnings.length > 0) err(`content: ${countLabel(warnings.length, 'warning')}
${formatErrors(warnings)}`);
    const expected = flag(argv, '--expect-counts');
    const actual = `aws=${result.counts.aws},microsoft=${result.counts.microsoft}`;
    if (expected !== undefined && expected !== actual) {
      err(`content: certification counts are ${actual}, expected ${expected}`);
      return 1;
    }
    write(join(root, 'src', 'app', 'content', 'generated'), result);
    out(`content: ${result.routes.length} routes, ${actual}, hash=${result.hash}`);
    return 0;
  } catch (error) {
    err(error instanceof ContentError ? error.message : `content: generation failed (${error.name})`);
    return 1;
  }
}
